//! Pairing: the four-phase handshake state machine and its PIN contract
//! (M1-T4).
//!
//! # Scope of this module
//!
//! This module owns everything about pairing that is **not** a byte-level
//! cryptographic detail:
//!
//! - the ordered phases a pending pairing moves through;
//! - explicit rejection of a request that arrives out of order;
//! - a pending-session TTL and a bounded store, so an abandoned pairing cannot
//!   accumulate forever (plan §7, "Pairing abandoned mid-flow");
//! - the events the IPC layer forwards to the panel (`pairing_pending`,
//!   `pairing_result` in [`plans/towards-0.2.0.md`] §5.1).
//!
//! # Provisional crypto
//!
//! The exact bytes of the GameStream pairing exchange — salts, nonce/IV
//! derivation, key derivation, and the challenge hash — are **not** guessed
//! here. They sit behind the [`PairingCrypto`] trait and are supplied by
//! [`ReferenceCrypto`], an intentionally provisional implementation that is
//! self-consistent and testable but is **not** claimed to interoperate with a
//! real Moonlight client.
//!
//! The M0 trace corpus (M0-T5) is what pins those bytes; when it lands, a
//! production `PairingCrypto` implementation is added and
//! [`ReferenceCrypto`] either becomes a test double or is replaced. Until then
//! no code outside `crypto.rs` changes, and the state machine below is already
//! the shape the real handshake needs.
//!
//! # Clean-room note
//!
//! No Sunshine or `moonlight-common-c` source is transcribed. The phase names
//! and the request paths they correspond to are part of the public protocol
//! and are declared in [`gs_http`]'s route table; the algorithm choices behind
//! the trait are this project's own until a capture says otherwise.

