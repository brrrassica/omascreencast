/// Why a pairing request could not be processed.
///
/// Variants are deliberately coarse: the IPC and HTTPS layers turn them into a
/// user-facing reason, and a too-specific error is a protocol hint an attacker
/// did not need.
#[derive(Debug, PartialEq, Eq, thiserror::Error)]
pub enum PairingError {
    /// No pending session has that id. It expired, was completed, or never
    /// existed.
    #[error("unknown pairing session")]
    UnknownSession,
    /// The session existed but its TTL has elapsed.
    #[error("pairing session expired")]
    Expired,
    /// A request arrived for a phase the session is not in.
    #[error("out of order: expected {expected:?}, received {received:?}")]
    OutOfOrder {
        /// The phase the session is currently in.
        expected: PairingPhase,
        /// The phase the rejected request belongs to.
        received: PairingPhase,
    },
    /// The operator's PIN was not exactly [`PIN_LENGTH`] decimal digits.
    #[error("PIN must be {PIN_LENGTH} decimal digits")]
    InvalidPin,
    /// The client's proof for the server challenge did not match.
    #[error("client failed the pairing challenge")]
    ChallengeRejected,
    /// The bounded pending store is full.
    #[error("at most {max} pairing sessions may be pending at once")]
    TooManyPending {
        /// The configured bound.
        max: usize,
    },
    /// A cryptographic primitive failed; the message never contains secrets.
    #[error("pairing crypto failed: {0}")]
    Crypto(String),
}

/// A four-digit PIN as entered by the operator.
///
/// # Flow note
///
/// Moonlight for Android TV *displays* the PIN and has no field to type one
/// into, so the operator reads it off the TV and gives it to the host. That is
/// why the PIN is supplied at approval time rather than generated by the host,
/// and why it is absent from the `pairing_pending` IPC event.
///
/// The value is redacted in both [`std::fmt::Debug`] and [`std::fmt::Display`]
/// so a PIN cannot leak into a trace by being formatted.
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct Pin {
    digits: [u8; PIN_LENGTH],
}

impl Pin {
    /// Validate an operator-supplied PIN.
    ///
    /// Only ASCII decimal digits are accepted. Leading zeros are kept, because
    /// `0420` is a different PIN from `420` and the client displays four
    /// characters.
    ///
    /// # Errors
    ///
    /// Returns [`PairingError::InvalidPin`] when the value is not exactly
    /// [`PIN_LENGTH`] digits.
    pub fn parse(value: &str) -> Result<Self, PairingError> {
        let bytes = value.as_bytes();
        if bytes.len() != PIN_LENGTH || !bytes.iter().all(u8::is_ascii_digit) {
            return Err(PairingError::InvalidPin);
        }
        let mut digits = [0u8; PIN_LENGTH];
        digits.copy_from_slice(bytes);
        Ok(Self { digits })
    }

    /// The PIN as ASCII digits, for key derivation only.
    ///
    /// Callers must not log the result; use the redacted `Display` instead.
    #[must_use]
    pub fn as_bytes(&self) -> &[u8; PIN_LENGTH] {
        &self.digits
    }
}

impl std::fmt::Debug for Pin {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Pin(****)")
    }
}

impl std::fmt::Display for Pin {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("****")
    }
}

/// An event for the IPC layer, serialised as one JSONL line (plan §5.1).
///
/// The tag is the `event` field, so a serialised [`PairingEvent::Pending`] is
/// exactly `{"event":"pairing_pending", ...}`. The panel's phase vocabulary is
/// unchanged; pairing events are additive.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "event")]
pub enum PairingEvent {
    /// A client asked to pair and is waiting for operator approval.
    #[serde(rename = "pairing_pending")]
    Pending {
        /// Pairing session id, opaque and short-lived.
        id: String,
        /// Client-reported device name, if it sent one.
        name: String,
        /// Source address the request arrived from.
        address: String,
    },
    /// A pairing attempt reached a terminal state.
    #[serde(rename = "pairing_result")]
    Result {
        /// Pairing session id that just finished.
        id: String,
        /// `true` on success, `false` on rejection or expiry.
        ok: bool,
    },
}

impl PairingEvent {
    /// Build a `pairing_pending` event from a pending session's summary.
    #[must_use]
    pub fn pending(info: &PendingInfo) -> Self {
        Self::Pending {
            id: info.id.clone(),
            name: info.name.clone(),
            address: info.address.clone(),
        }
    }

    /// Build a `pairing_result` event.
    #[must_use]
    pub fn result(id: impl Into<String>, ok: bool) -> Self {
        Self::Result { id: id.into(), ok }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pin_accepts_exactly_four_decimal_digits() {
        let pin = Pin::parse("0420").unwrap();
        assert_eq!(pin.as_bytes(), b"0420");
        for bad in ["", "123", "12345", "12a4", "-123", " 123", "١٢٣٤"] {
            assert_eq!(Pin::parse(bad), Err(PairingError::InvalidPin), "{bad:?}");
        }
    }

    #[test]
    fn pin_is_redacted_in_debug_and_display() {
        let pin = Pin::parse("2468").unwrap();
        assert_eq!(format!("{pin:?}"), "Pin(****)");
        assert_eq!(format!("{pin}"), "****");
        assert!(!format!("{pin:?}{pin}").contains("2468"));
    }

    #[test]
    fn pending_event_matches_the_ipc_contract() {
        let info = PendingInfo {
            id: "9f2c".to_owned(),
            name: "Living Room TV".to_owned(),
            address: "192.168.1.40".to_owned(),
        };
        let json = serde_json::to_value(PairingEvent::pending(&info)).unwrap();
        assert_eq!(
            json,
            serde_json::json!({
                "event": "pairing_pending",
                "id": "9f2c",
                "name": "Living Room TV",
                "address": "192.168.1.40",
            })
        );
    }

    #[test]
    fn result_event_matches_the_ipc_contract() {
        let json = serde_json::to_value(PairingEvent::result("abc", true)).unwrap();
        assert_eq!(
            json,
            serde_json::json!({"event": "pairing_result", "id": "abc", "ok": true})
        );
    }

    #[test]
    fn events_round_trip_through_json() {
        for event in [
            PairingEvent::result("x", false),
            PairingEvent::Pending {
                id: "1".to_owned(),
                name: "TV".to_owned(),
                address: "10.0.0.2".to_owned(),
            },
        ] {
            let text = serde_json::to_string(&event).unwrap();
            let parsed: PairingEvent = serde_json::from_str(&text).unwrap();
            assert_eq!(parsed, event);
        }
    }
}
